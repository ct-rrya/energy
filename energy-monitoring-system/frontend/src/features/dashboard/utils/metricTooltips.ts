/**
 * Metric Tooltips - Witty, Contextual, and Value-Aware Dashboard Tooltips
 * 
 * Design Principle: "One metric. One interesting observation. One relatable sentence."
 * 
 * Replaces lengthy documentation paragraphs with concise, dynamic, and technically
 * accurate real-world observations based on actual current readings.
 */

/**
 * Generates a dynamic, relatable observation for the Steps Today metric.
 * 
 * @param steps - Total footsteps detected today
 * @returns Short, witty observation matching the foot traffic level
 */
export function getStepsTooltip(steps?: number): string {
  if (steps === undefined || steps === 0) {
    return 'Zero footsteps so far today. The tile is resting peacefully, waiting for its first walker.';
  }
  if (steps === 1) {
    return '1 footstep recorded! Every journey of clean energy begins with a single step.';
  }
  if (steps < 100) {
    return `${steps.toLocaleString()} footsteps so far. A gentle start to the day's pedestrian energy harvest.`;
  }
  if (steps < 1000) {
    return `${steps.toLocaleString()} footsteps! That's more foot traffic than a busy neighborhood crosswalk.`;
  }
  if (steps < 5000) {
    return `${steps.toLocaleString()} footsteps! The tile has been busier than a university hallway between lectures.`;
  }
  return `${steps.toLocaleString()} footsteps! That's a full-on campus marathon across a single tile.`;
}

/**
 * Generates a dynamic, relatable observation for the Power Output metric.
 * 
 * @param powerMw - Current instantaneous power output in milliwatts
 * @param hasActivity - Whether the tile has active movement
 * @returns Short, witty observation reflecting the live power generation rate
 */
export function getPowerTooltip(powerMw?: number, hasActivity?: boolean): string {
  const p = powerMw ?? 0;
  if (!hasActivity || p < 0.1) {
    return '0.0 mW right now. The tile is at rest — electricity sparks the moment someone steps down.';
  }
  if (p < 20) {
    return `${p.toFixed(1)} mW generated right now. Small power, big potential — footsteps turning into electricity, one step at a time.`;
  }
  if (p < 100) {
    return `${p.toFixed(1)} mW of instantaneous power. Footsteps are actively converting walking momentum into electrical current.`;
  }
  return `${p.toFixed(1)} mW peak! A solid, energetic step sending a strong electrical pulse into the circuit.`;
}

/**
 * Generates a dynamic, technically accurate observation for the Energy Today metric.
 * 
 * Benchmarks:
 * - 1 mWh = 3.6 Joules
 * - Standard smartphone battery: 12 Wh (3,240 mAh at 3.7 V)
 * - Assumes ~85% theoretical charging circuit efficiency
 * - Ultra-low-power IoT beacon transmission: ~0.05 mWh
 * - Low-power digital quartz watch: ~35 mWh capacity
 * 
 * @param energyWh - Accumulated clean energy today in Watt-hours
 * @returns Concise comparison distinguishing theoretical estimates from actual charging capability
 */
export function getEnergyTodayTooltip(energyWh?: number): string {
  const rawWh = energyWh ?? 0;
  if (rawWh <= 0) {
    return '0 mWh accumulated today. Every step will bank a fraction of a milliwatt-hour into the storage capacitors.';
  }

  const mWh = rawWh * 1000;

  if (mWh < 1) {
    return `${mWh.toFixed(2)} mWh banked today. Every single step adds another tiny drop into the clean energy reservoir.`;
  }
  if (mWh < 10) {
    return `${mWh.toFixed(1)} mWh harvested so far. That's enough clean energy to pulse an ultra-low-power IoT beacon dozens of times.`;
  }
  if (mWh < 500) {
    return `${mWh.toFixed(0)} mWh stored! Theoretically equivalent to running a low-power digital watch for days, powered purely by foot traffic.`;
  }

  // 500 mWh (0.5 Wh) and above: realistic smartphone battery theoretical comparison
  const SMARTPHONE_BATTERY_WH = 12.0; // Standard ~3,240 mAh @ 3.7 V
  const CHARGING_EFFICIENCY = 0.85;
  const theoreticalPhonePct = Math.min(100, (rawWh / SMARTPHONE_BATTERY_WH) * 100 * CHARGING_EFFICIENCY);

  return `${rawWh.toFixed(2)} Wh accumulated! Theoretically enough energy to trickle-charge about ${theoreticalPhonePct.toFixed(1)}% of a standard 12 Wh smartphone battery.`;
}

/**
 * Generates a dynamic, relatable observation for the Voltage metric.
 * 
 * @param voltage - Electric potential in Volts
 * @returns Concise observation on the electrical push generated by footsteps
 */
export function getVoltageTooltip(voltage?: number): string {
  const v = voltage ?? 0;
  if (v < 0.2) {
    return '0.0 V at rest. The piezoelectric ceramic crystals are waiting for mechanical compression to generate electric charge.';
  }
  if (v < 2.5) {
    return `${v.toFixed(2)} V detected. Gentle pressure on the tile is pushing electrons through the rectifier bridge.`;
  }
  if (v < 6.0) {
    return `${v.toFixed(2)} V generated. That's comparable to a standard USB power rail, produced by footsteps alone.`;
  }
  return `${v.toFixed(2)} V peak! Strong impact force is creating a robust voltage spike across the crystal lattice.`;
}

/**
 * Generates a dynamic, relatable observation for the Current metric.
 * 
 * @param currentMa - Electric current in Milliamps
 * @returns Concise observation on the rate of electrical charge flow
 */
export function getCurrentTooltip(currentMa?: number): string {
  const ma = currentMa ?? 0;
  if (ma < 0.1) {
    return '0.0 mA at rest. No electrical charge is currently flowing through the conditioning circuit.';
  }
  if (ma < 5.0) {
    return `${ma.toFixed(1)} mA flowing. A subtle trickle of electrons moving from the tile into the capacitor bank.`;
  }
  return `${ma.toFixed(1)} mA discharge rate. A lively burst of electron flow transferring harvested energy into storage.`;
}

/**
 * Generates a dynamic observation for the "Your EcoStep Today" summary card.
 * 
 * @param steps - Step count recorded today
 * @param energyWh - Energy harvested today in Wh
 * @returns Concise summary observation
 */
export function getGlanceTooltip(steps?: number, energyWh?: number): string {
  const s = steps ?? 0;
  const e = energyWh ?? 0;
  if (s === 0 && e <= 0) {
    return 'A quiet day so far. The tiles are calibrated and standing by for the day\'s first steps.';
  }
  return `${s.toLocaleString()} steps translated into clean energy today. Every compression adds to the campus micro-generation total.`;
}

