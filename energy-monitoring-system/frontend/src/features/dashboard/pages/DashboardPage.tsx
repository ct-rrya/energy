
import { useEffect, useState } from 'react';
import { useAuth } from '@/contexts/AuthContext';
import { getUserRole } from '@/lib/permissions';
import { useDashboardMetrics } from '../hooks/useDashboardMetrics';
import { useSystemHealth } from '../hooks/useSystemHealth';
import { useLiveSensorData } from '../hooks/useLiveSensorData';
import { DashboardHeader } from '../components/DashboardHeader';
import { MetricCard } from '../components/MetricCard';
import { HeroPowerCard } from '../components/HeroPowerCard';
import { DashboardErrorBoundary } from '../components/DashboardErrorBoundary';
import { validateSensorData } from '../utils/validateSensorData';
import type { SensorReading } from '../types/dashboard.types';
import { HowHarvestingWorksCard } from '../components/HowHarvestingWorksCard';
import {
  getStepsTooltip,
  getEnergyTodayTooltip,
  getVoltageTooltip,
  getCurrentTooltip,
} from '../utils/metricTooltips';

/**
 * EcoStep Dashboard Page - Hero Power Dashboard
 * 
 * Real-time monitoring dashboard with hero-focused layout.
 * Power output (mW) is the primary KPI displayed prominently in a large hero card with AI insights.
 * 
 * Layout Structure:
 * - Header: Title, subtitle, date/time, system status badge
 * - Hero Section (60% width desktop): Large power card with AI insight
 * - Metrics Column (40% width desktop): Three stacked metric cards (Steps, Voltage, Current)
 * - Desktop: Side-by-side layout with 24px gap
 * - Tablet: Power hero above, 3 metrics in row below
 * - Mobile: Fully stacked vertical layout
 * 
 * Visual Hierarchy:
 * - Hero power card is approximately 2x larger than individual metric cards
 * - Typography size differences establish hierarchy
 * - Clean, data-first design with AI-generated insights
 * 
 * Data Handling:
 * - Real-time sensor data via WebSocket
 * - Daily metrics and AI insights via REST API
 * - Last-known-good data caching for fallback
 * - Data validation before rendering
 * 
 * AI Analysis:
 * - Power-focused insights generated by backend
 * - Displayed within hero card
 * - Loading states and error handling preserved
 * - Automatic refresh with new data
 */
function DashboardPageContent() {
  const { isAuthenticated, user } = useAuth();

  // Determine user role (Requirements 18.1-18.7)
  const userRole = getUserRole(isAuthenticated, user);
  const isPublicUser = userRole === 'public';

  // Fetch dashboard data with error and loading states (Requirements 16.1-16.3, 17.1-17.5)
  const {
    data: metrics,
  } = useDashboardMetrics();

  const {
    data: systemStatus,
  } = useSystemHealth();

  const { lastReading, isConnected: isWebSocketConnected } = useLiveSensorData();

  // Last known good data cache for fallback (Requirements 19.2, 19.5)
  const [lastGoodReading, setLastGoodReading] = useState<SensorReading | undefined>(undefined);
  const [lastGoodMetrics, setLastGoodMetrics] = useState<typeof metrics>(undefined);

  // Update cache when new valid data arrives (Requirements 19.4, 19.6)
  useEffect(() => {
    if (lastReading) {
      const validationResult = validateSensorData(lastReading);
      if (validationResult.isValid) {
        // eslint-disable-next-line react-hooks/set-state-in-effect
        setLastGoodReading(lastReading);
      } else {
        console.warn('[Dashboard] Sensor reading validation failed:', validationResult.errors);
      }
    }
  }, [lastReading]);

  // Metrics validation function (Requirement 17.6)
  const validateMetrics = (data: typeof metrics): boolean => {
    if (!data) return false;

    // Validate dailyEnergy is reasonable (0-1000 kWh)
    if (data.dailyEnergy !== undefined && (data.dailyEnergy < 0 || data.dailyEnergy > 1000)) {
      console.warn('[Dashboard] Invalid daily energy value:', data.dailyEnergy);
      return false;
    }

    return true;
  };

  useEffect(() => {
    if (metrics && validateMetrics(metrics)) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLastGoodMetrics(metrics);
    }
  }, [metrics]);

  // Use cached data as fallback when validation fails (Requirements 19.2, 19.6)
  const displayReading = (() => {
    // If no activity today, don't show stale readings from previous days
    const todaySteps = metrics?.todayTotalSteps ?? lastGoodMetrics?.todayTotalSteps;
    const hasActivityToday = todaySteps !== undefined && todaySteps > 0;

    if (!hasActivityToday) {
      // No activity today - return undefined to show empty state
      return undefined;
    }

    // Has activity today - validate and use current or cached reading
    if (lastReading) {
      const validationResult = validateSensorData(lastReading);
      if (validationResult.isValid) {
        return lastReading;
      }
    }
    return lastGoodReading;
  })();

  const displayMetrics = metrics && validateMetrics(metrics)
    ? metrics
    : lastGoodMetrics;

  // Determine system status for header (Requirements 2.6-2.9)
  const getSystemStatus = (): 'connected' | 'disconnected' | 'unknown' => {
    if (systemStatus?.database === 'connected') return 'connected';
    if (systemStatus?.database === 'disconnected') return 'disconnected';
    return 'unknown';
  };

  return (
    <div className="page">
      {/* Dashboard Header with date/time and system status (Requirements 2.1-2.9) */}
      <DashboardHeader
          title="EcoStep Central"
          subtitle="Real-time monitoring of piezoelectric energy harvesting system"
          systemStatus={getSystemStatus()}
          isPublicUser={isPublicUser}
          isWebSocketConnected={isWebSocketConnected}
        />

        {/* Main Metrics Grid - Container Query Driven */}
        <style>{`
          .dashboard-metrics-grid {
            display: flex;
            flex-direction: column;
            gap: 16px;
            width: 100%;
            min-width: 0;
          }
          
          .metric-hero-power {
            width: 100%;
            min-width: 0;
          }
          
          .dashboard-secondary-metrics {
            width: 100%;
            min-width: 0;
            display: grid;
            grid-template-columns: repeat(4, 1fr);
            gap: 16px;
          }

          @container (max-width: 899px) {
            .dashboard-secondary-metrics {
              grid-template-columns: repeat(2, minmax(0, 1fr));
            }
          }

          @media (max-width: 768px) {
            .dashboard-secondary-metrics {
              grid-template-columns: repeat(2, minmax(0, 1fr)) !important;
              gap: 12px;
            }
          }
        `}</style>

        <div className="dashboard-metrics-grid">

          {/* Hero Power Card - Prominent display with AI analysis */}
          <div className="metric-hero-power">
            <HeroPowerCard
              powerValue={displayReading?.power}
              previousPower={undefined}
              aiInsight={displayMetrics?.aiInsight}
              isLoading={false}
              todaySteps={displayMetrics?.todayTotalSteps}
            />
          </div>

          {/* Secondary Metrics - Steps, Energy Today, Voltage, Current */}
          <div className="dashboard-secondary-metrics">

            {/* Step Count */}
            <div className="metric-steps min-w-0">
              <MetricCard
                label="Steps Today"
                plainDescription="Footsteps on Tile"
                tooltip={{
                  title: "Steps Today",
                  description: getStepsTooltip(displayMetrics?.todayTotalSteps),
                }}
                value={displayMetrics?.todayTotalSteps}
                unit=""
                precision={0}
                color="accent"
                dotColor="#19D46A"
                subtitle={
                  displayMetrics?.todayTotalSteps === undefined || displayMetrics?.todayTotalSteps === 0
                    ? "No steps yet today"
                    : undefined
                }
              />
            </div>

            {/* Daily Harvested Energy -> Explicitly "Energy Today" */}
            <div className="metric-energy min-w-0">
              {(() => {
                const rawEnergy = displayMetrics?.dailyEnergy ?? 0;
                const isMilliWh = rawEnergy < 1;
                const displayVal = isMilliWh ? rawEnergy * 1000 : rawEnergy;
                return (
                  <MetricCard
                    label="Energy Today"
                    plainDescription="Total Stored Clean Energy"
                    tooltip={{
                      title: isMilliWh ? "Energy Today (mWh)" : "Energy Today (Wh)",
                      description: getEnergyTodayTooltip(rawEnergy),
                    }}
                    value={displayMetrics?.dailyEnergy !== undefined ? displayVal : undefined}
                    unit={isMilliWh ? "mWh" : "Wh"}
                    precision={isMilliWh ? 2 : 3}
                    color="amber"
                    dotColor="#A6DC3C"
                    subtitle={
                      displayMetrics?.dailyEnergy === undefined || displayMetrics?.dailyEnergy === 0
                        ? "Awaiting footsteps"
                        : undefined
                    }
                  />
                );
              })()}
            </div>

            {/* Voltage */}
            <div className="metric-voltage min-w-0">
              <MetricCard
                label="Voltage"
                plainDescription="Electrical Push"
                tooltip={{
                  title: "Voltage (Volts)",
                  description: getVoltageTooltip(displayReading?.voltage),
                }}
                value={displayReading?.voltage}
                unit="V"
                precision={2}
                color="accent"
                dotColor="#13B95C"
                subtitle={
                  displayReading?.voltage === undefined
                    ? "Waiting for data"
                    : undefined
                }
              />
            </div>

            {/* Current */}
            <div className="metric-current min-w-0">
              <MetricCard
                label="Current"
                plainDescription="Charge Flow Rate"
                tooltip={{
                  title: "Current (Milliamps)",
                  description: getCurrentTooltip(displayReading?.current ? displayReading.current * 1000 : undefined),
                }}
                value={displayReading?.current ? displayReading.current * 1000 : undefined}
                unit="mA"
                precision={1}
                color="blue"
                dotColor="#7FE0A8"
                subtitle={
                  displayReading?.current === undefined || displayReading?.current === 0
                    ? "Discharge at rest"
                    : undefined
                }
              />
            </div>

          </div>

        </div>

        {/* Educational Process: How EcoStep Footstep Harvesting Works */}
        <HowHarvestingWorksCard />

    </div>
  );
}

/**
 * Dashboard Page with Error Boundary
 * Wraps DashboardPageContent with error boundary for error handling
 * Requirements: 19.1 - Error boundary at page level
 */
export function DashboardPage() {
  return (
    <DashboardErrorBoundary onReset={() => window.location.reload()}>
      <DashboardPageContent />
    </DashboardErrorBoundary>
  );
}