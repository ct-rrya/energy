
import { useEffect, useState } from 'react';
import { Settings2, Sparkles, Lock } from 'lucide-react';
import { useAuth } from '@/contexts/AuthContext';
import { useHardwareStatus } from '@/contexts/HardwareStatusContext';
import { getUserRole, isAdmin } from '@/lib/permissions';
import { useDashboardMetrics } from '../hooks/useDashboardMetrics';
import { useLiveSensorData } from '../hooks/useLiveSensorData';
import { DashboardHeader } from '../components/DashboardHeader';
import { MetricCard } from '../components/MetricCard';
import { HeroPowerCard } from '../components/HeroPowerCard';
import { DashboardErrorBoundary } from '../components/DashboardErrorBoundary';
import { validateSensorData } from '../utils/validateSensorData';
import type { SensorReading } from '../types/dashboard.types';
import { HowHarvestingWorksCard } from '../components/HowHarvestingWorksCard';
import { MilestonesRoadmap } from '@/features/milestones/components/MilestonesRoadmap';
import { AdminMilestonesModal } from '@/features/milestones/components/AdminMilestonesModal';
import { useMilestones } from '@/features/milestones/hooks/useMilestones';
import {
  getStepsTooltip,
  getEnergyTodayTooltip,
  getVoltageTooltip,
  getCurrentTooltip,
} from '../utils/metricTooltips';

/**
 * EcoStep Dashboard Page - Hero Power Dashboard
 * 
 * Real-time monitoring dashboard with hero-focused layout.
 * Power output (mW) is the primary KPI displayed prominently in a large hero card with AI insights.
 * 
 * Layout Structure:
 * - Header: Title, subtitle, date/time, system status badge
 * - Hero Section (60% width desktop): Large power card with AI insight
 * - Metrics Column (40% width desktop): Three stacked metric cards (Steps, Voltage, Current)
 * - Desktop: Side-by-side layout with 24px gap
 * - Tablet: Power hero above, 3 metrics in row below
 * - Mobile: Fully stacked vertical layout
 * 
 * Visual Hierarchy:
 * - Hero power card is approximately 2x larger than individual metric cards
 * - Typography size differences establish hierarchy
 * - Clean, data-first design with AI-generated insights
 * 
 * Data Handling:
 * - Real-time sensor data via WebSocket
 * - Daily metrics and AI insights via REST API
 * - Last-known-good data caching for fallback
 * - Data validation before rendering
 * 
 * AI Analysis:
 * - Power-focused insights generated by backend
 * - Displayed within hero card
 * - Loading states and error handling preserved
 * - Automatic refresh with new data
 */
function DashboardPageContent() {
  const { isAuthenticated, user } = useAuth();

  // Determine user role (Requirements 18.1-18.7)
  const userRole = getUserRole(isAuthenticated, user);
  const isAdminUser = isAdmin(isAuthenticated, user);
  const isPublicUser = userRole === 'public';

  // Current-month milestone journey data (combined into Central)
  const milestoneData = useMilestones();
  const [isMilestoneModalOpen, setIsMilestoneModalOpen] = useState(false);
  const isAutoCalculated = Boolean(milestoneData.configurationPolicy?.isAutoCalculated);
  const autoFromLabel = milestoneData.configurationPolicy?.autoCalculatedFromLabel;
  const growthPct = milestoneData.configurationPolicy?.growthPercent ?? 10;

  // Fetch dashboard data with error and loading states (Requirements 16.1-16.3, 17.1-17.5)
  const {
    data: metrics,
  } = useDashboardMetrics();

  const { lastReading } = useLiveSensorData();

  // Last known good data cache for fallback (Requirements 19.2, 19.5)
  const [lastGoodReading, setLastGoodReading] = useState<SensorReading | undefined>(undefined);
  const [lastGoodMetrics, setLastGoodMetrics] = useState<typeof metrics>(undefined);

  // Update cache when new valid data arrives (Requirements 19.4, 19.6)
  useEffect(() => {
    if (lastReading) {
      const validationResult = validateSensorData(lastReading);
      if (validationResult.isValid) {
        // eslint-disable-next-line react-hooks/set-state-in-effect
        setLastGoodReading(lastReading);
      } else {
        console.warn('[Dashboard] Sensor reading validation failed:', validationResult.errors);
      }
    }
  }, [lastReading]);

  // Metrics validation function (Requirement 17.6)
  const validateMetrics = (data: typeof metrics): boolean => {
    if (!data) return false;

    // Validate dailyEnergy is reasonable (0-1000 kWh)
    if (data.dailyEnergy !== undefined && (data.dailyEnergy < 0 || data.dailyEnergy > 1000)) {
      console.warn('[Dashboard] Invalid daily energy value:', data.dailyEnergy);
      return false;
    }

    return true;
  };

  useEffect(() => {
    if (metrics && validateMetrics(metrics)) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLastGoodMetrics(metrics);
    }
  }, [metrics]);

  // Use cached data as fallback when validation fails (Requirements 19.2, 19.6)
  const displayReading = (() => {
    // Show reading if today's metrics have steps OR if the live reading itself is from today
    const todaySteps = metrics?.todayTotalSteps ?? lastGoodMetrics?.todayTotalSteps;
    const candidateReading = lastReading ?? lastGoodReading;
    const isCandidateFromToday = candidateReading?.timestamp
      ? new Date(candidateReading.timestamp).toDateString() === new Date().toDateString()
      : false;
    const hasActivityToday =
      (todaySteps !== undefined && todaySteps > 0) || isCandidateFromToday;

    if (!hasActivityToday) {
      // No activity today - return undefined to show empty state
      return undefined;
    }

    // Has activity today - validate and use current or cached reading
    if (lastReading) {
      const validationResult = validateSensorData(lastReading);
      if (validationResult.isValid) {
        return lastReading;
      }
    }
    return lastGoodReading;
  })();

  const displayMetrics = metrics && validateMetrics(metrics)
    ? metrics
    : lastGoodMetrics;

  // Single source of truth for hardware connection status
  const { status: hardwareConnectionStatus } = useHardwareStatus();

  return (
    <div className="page">
      {/* Dashboard Header with date/time and standardized hardware status */}
      <DashboardHeader
        title="EcoStep Central"
        subtitle="Live footstep energy monitoring"
        systemStatus={hardwareConnectionStatus}
        isPublicUser={isPublicUser}
      />

      {/* Main Metrics Grid - Full-Width Stacked Layout with Equal-Size Metric Cards */}
      <style>{`
          .dashboard-metrics-grid {
            display: flex;
            flex-direction: column;
            gap: 16px;
            width: 100%;
            min-width: 0;
          }

          .dashboard-live-row {
            display: flex;
            flex-direction: column;
            gap: 16px;
            width: 100%;
            min-width: 0;
          }

          .metric-hero-power {
            width: 100%;
            min-width: 0;
          }

          .dashboard-secondary-metrics {
            width: 100%;
            min-width: 0;
            display: grid;
            grid-template-columns: repeat(4, minmax(0, 1fr));
            grid-auto-rows: 1fr;
            gap: 0;
            border: 1px solid var(--line);
            border-radius: 14px;
            background: var(--card-bg);
            overflow: hidden;
          }

          .dashboard-secondary-metrics > div {
            height: 100%;
            display: flex;
            flex-direction: column;
            border-right: 1px solid var(--line);
          }

          .dashboard-secondary-metrics > div:last-child {
            border-right: none;
          }

          @container (max-width: 899px) {
            .dashboard-secondary-metrics {
              grid-template-columns: repeat(2, minmax(0, 1fr));
            }
            .dashboard-secondary-metrics > div:nth-child(2n) {
              border-right: none;
            }
            .dashboard-secondary-metrics > div:nth-child(-n+2) {
              border-bottom: 1px solid var(--line);
            }
          }

          @media (max-width: 768px) {
            .dashboard-secondary-metrics {
              grid-template-columns: repeat(2, minmax(0, 1fr)) !important;
              gap: 0;
            }
            .dashboard-secondary-metrics > div:nth-child(2n) {
              border-right: none;
            }
            .dashboard-secondary-metrics > div:nth-child(-n+2) {
              border-bottom: 1px solid var(--line);
            }
          }
        `}</style>

      <div className="dashboard-metrics-grid">

        {/* Main Hero Card: Current Month Energy Milestone Journey */}
        <div className="w-full min-w-0 space-y-2.5">
          {(isAutoCalculated || isAdminUser) && (
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex items-center flex-wrap gap-2">
                {isAutoCalculated && (
                  <span
                    className="pill text-[10px] font-bold text-emerald-700 dark:text-emerald-300 bg-emerald-500/10 border border-emerald-500/20 flex items-center gap-1"
                    title="Automatically calculated from the previous month's harvested energy plus 10% growth"
                  >
                    <Sparkles className="w-2.5 h-2.5" />
                    {autoFromLabel
                      ? `AUTO: ${autoFromLabel.toUpperCase()} +${growthPct}%`
                      : `AUTO TARGET (+${growthPct}%)`}
                  </span>
                )}
                {isAdminUser && milestoneData.isLocked && (
                  <span className="pill text-[10px] font-bold text-emerald-700 dark:text-emerald-300 bg-emerald-500/10 border border-emerald-500/20 flex items-center gap-1">
                    <Lock className="w-2.5 h-2.5" />
                    CUSTOM TARGET
                  </span>
                )}
              </div>

              {isAdminUser && (
                <button
                  type="button"
                  onClick={() => setIsMilestoneModalOpen(true)}
                  className="min-h-[32px] px-3 rounded-full text-xs font-semibold flex items-center gap-1.5 transition-colors shadow-sm bg-[var(--acc)] text-white dark:text-[#04210f] hover:opacity-90 cursor-pointer"
                  title="Adjust monthly and weekly targets"
                >
                  <Settings2 className="w-3.5 h-3.5" />
                  <span>{milestoneData.isLocked ? 'Adjust Goal' : 'Customize Goal'}</span>
                </button>
              )}
            </div>
          )}

          <MilestonesRoadmap
            selectedMonth={milestoneData.currentMonth || milestoneData.selectedMonth}
            milestoneData={milestoneData}
            isAdmin={isAdminUser}
            compact
          />
        </div>

        {/* Live Row: Power Output (Left) + Steps, Energy Today, Voltage, Current */}
        <div className="dashboard-live-row">
          <div className="metric-hero-power">
            <HeroPowerCard
              powerValue={
                displayReading?.power !== undefined
                  ? displayReading.power * 1000
                  : undefined
              }
              previousPower={undefined}
              aiInsight={displayMetrics?.aiInsight}
              isLoading={false}
              todaySteps={displayMetrics?.todayTotalSteps ?? displayReading?.stepCount}
              connectionStatus={hardwareConnectionStatus}
            />
          </div>

        {/* Secondary Metrics - Steps, Energy Today, Voltage, Current */}
        <div className="dashboard-secondary-metrics">

          {/* Step Count */}
          <div className="metric-steps min-w-0">
            <MetricCard
              inline
              label="Steps Today"
              plainDescription="Footsteps on Tile"
              tooltip={{
                title: "Steps Today",
                description: getStepsTooltip(displayMetrics?.todayTotalSteps),
              }}
              value={displayMetrics?.todayTotalSteps ?? displayReading?.stepCount}
              unit=""
              precision={0}
              color="accent"
              dotColor="#19D46A"
              subtitle={
                (displayMetrics?.todayTotalSteps ?? displayReading?.stepCount ?? 0) === 0
                  ? "No steps yet today"
                  : undefined
              }
            />
          </div>

          {/* Daily Harvested Energy -> Explicitly "Energy Today" */}
          <div className="metric-energy min-w-0">
            {(() => {
              const energyFromMetricsMWh =
                displayMetrics?.todayEnergyMWh !== undefined
                  ? displayMetrics.todayEnergyMWh
                  : displayMetrics?.dailyEnergy !== undefined
                  ? displayMetrics.dailyEnergy * 1_000_000
                  : undefined;
              const energyMWh =
                energyFromMetricsMWh !== undefined && energyFromMetricsMWh > 0
                  ? energyFromMetricsMWh
                  : displayReading?.energy && displayReading.energy > 0
                  ? displayReading.energy
                  : energyFromMetricsMWh ?? 0;
              const energyWh = energyMWh / 1000;
              const ledSeconds = Math.round(energyMWh * 180); // ~20 mW indicator LED = 180 sec per mWh
              const ledSubtitle =
                energyMWh <= 0
                  ? '~50 steps lights a small LED (1s)'
                  : ledSeconds >= 60
                  ? `≈ ${(ledSeconds / 60).toFixed(1)} min of a small LED`
                  : `≈ ${Math.max(1, ledSeconds)} sec of a small LED`;
              const energyPrecision = 5;
              return (
                <MetricCard
                  inline
                  label="Energy Today"
                  plainDescription="Total Stored Clean Energy"
                  tooltip={{
                    title: 'Energy Today (mWh)',
                    description: getEnergyTodayTooltip(energyWh),
                  }}
                  value={
                    energyFromMetricsMWh !== undefined || displayReading?.energy !== undefined
                      ? energyMWh
                      : undefined
                  }
                  unit="mWh"
                  precision={energyPrecision}
                  color="amber"
                  dotColor="#A6DC3C"
                  subtitle={ledSubtitle}
                />
              );
            })()}
          </div>

          {/* Voltage */}
          <div className="metric-voltage min-w-0">
            <MetricCard
              inline
              label="Voltage"
              plainDescription="Electrical Push"
              tooltip={{
                title: "Voltage (Volts)",
                description: getVoltageTooltip(displayReading?.voltage),
              }}
              value={displayReading?.voltage}
              unit="V"
              precision={5}
              color="accent"
              dotColor="#13B95C"
              subtitle={
                displayReading?.voltage === undefined
                  ? "Waiting for footsteps"
                  : undefined
              }
            />
          </div>

          {/* Current */}
          <div className="metric-current min-w-0">
            <MetricCard
              inline
              label="Current"
              plainDescription="Charge Flow Rate"
              tooltip={{
                title: "Current (Milliamps)",
                description: getCurrentTooltip(displayReading?.current ? displayReading.current * 1000 : undefined),
              }}
              value={displayReading?.current ? displayReading.current * 1000 : undefined}
              unit="mA"
              precision={5}
              color="blue"
              dotColor="#7FE0A8"
              subtitle={
                displayReading?.current === undefined || displayReading?.current === 0
                  ? "No current flowing"
                  : undefined
              }
            />
          </div>

        </div>
        </div>

      </div>

      {/* Educational Process: How EcoStep Footstep Harvesting Works */}
      <HowHarvestingWorksCard />

      {/* Admin Milestone Target Configuration Modal */}
      {isAdminUser && (
        <AdminMilestonesModal
          isOpen={isMilestoneModalOpen}
          onClose={() => setIsMilestoneModalOpen(false)}
          activeMonth={milestoneData.currentMonth || milestoneData.selectedMonth}
          availableMonths={milestoneData.availableMonths}
          currentMonthTargetMWh={milestoneData.monthlyMilestone?.targetMWh ?? 0.1}
          currentWeeklyTargetMWh={milestoneData.weeklyMilestones[0]?.targetMWh ?? 0.025}
          configurationPolicy={milestoneData.configurationPolicy}
          onSave={async (payload) => {
            await milestoneData.updateTargets(payload);
          }}
        />
      )}

    </div>
  );
}

/**
 * Dashboard Page with Error Boundary
 * Wraps DashboardPageContent with error boundary for error handling
 * Requirements: 19.1 - Error boundary at page level
 */
export function DashboardPage() {
  return (
    <DashboardErrorBoundary onReset={() => window.location.reload()}>
      <DashboardPageContent />
    </DashboardErrorBoundary>
  );
}