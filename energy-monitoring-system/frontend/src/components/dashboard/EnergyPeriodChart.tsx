import React, { useMemo } from 'react';
import { useTheme } from '@/contexts/ThemeContext';
import { useMediaQuery } from '@/hooks/useMediaQuery';
import { useEnergyByPeriod, type PeriodFilter } from '@/features/dashboard/hooks/useEnergyByPeriod';
import { useChartRealTimeUpdates } from '@/features/dashboard/hooks/useChartRealTimeUpdates';
import {
  transformToChartData,
  isDatasetEmpty,
  hasDuplicateFormattedDates,
  formatSmartChartTimestamp,
  computeNiceYAxis,
} from './chartUtils';
import { ChartContainer } from './ChartContainer';
import { CustomChartTooltip } from './CustomChartTooltip';
import type { EnergyPeriodChartProps } from './chartTypes';
import {
  ResponsiveContainer,
  BarChart,
  CartesianGrid,
  XAxis,
  YAxis,
  Bar,
  Tooltip,
} from 'recharts';

/**
 * EnergyPeriodChart Component
 * 
 * Displays energy generation aggregated by different time periods.
 * Users can switch between Hourly, Daily, and Weekly views to compare production
 * across hours, days, or weeks.
 * 
 * Requirements:
 * - 4.1: Render as BarChart using Recharts BarChart component
 * - 4.2: Fetch data from Time_Series_API with metric parameter set to "energy"
 * - 4.3: Display three period filter options: "Hourly", "Daily", "Weekly"
 * - 4.4-4.6: Fetch appropriate data based on period filter selection
 * - 4.7: Display energy values in milliwatt-hours (mWh) on Y-axis
 * - 4.8: Display time period labels on X-axis
 * - 4.9: Use bar colors from EcoStep Design System with theme-appropriate shading
 * - 4.10: Use TanStack_Query for data fetching with appropriate caching
 * - 4.11: Refetch data when period filter changes
 * - 11.3: Apply theme-appropriate colors
 * 
 * @component
 * @example
 * ```tsx
 * <EnergyPeriodChart />
 * ```
 */
export const EnergyPeriodChart = React.memo(function EnergyPeriodChart({
  className = '',
  defaultPeriodFilter = 'daily',
  startDate,
  endDate,
  granularity: propGranularity,
  periodLabel,
  startHour,
  endHour,
}: EnergyPeriodChartProps) {
  const { theme } = useTheme();
  const isMobile = useMediaQuery('(max-width: 767px)');

  // Use defaultPeriodFilter ('daily' by default) - Analytics page controls the unified period
  const periodFilter: PeriodFilter = defaultPeriodFilter;

  // Subscribe to real-time WebSocket updates for chart data
  // This hook invalidates TanStack Query cache when new sensor readings arrive,
  // triggering automatic refetch of chart data for live updates
  useChartRealTimeUpdates();

  // Fetch energy data based on current period filter or unified page period
  const { data: timeSeries, isLoading, error, refetch } = useEnergyByPeriod(
    periodFilter,
    startDate && endDate
      ? { startDate, endDate, granularity: propGranularity, startHour, endHour }
      : startHour !== undefined && endHour !== undefined
        ? { startHour, endHour }
        : undefined
  );

  // Transform API data to chart format
  const chartData = useMemo(() => transformToChartData(timeSeries), [timeSeries]);

  // Determine if dataset is empty or sparse (< 2 points)
  const isEmpty = useMemo(() => isDatasetEmpty(chartData), [chartData]);
  const isSparse = chartData.length > 0 && chartData.length < 2;
  const chartHeight = isMobile ? 240 : 270;

  // Determine granularity from prop or default to 'day'
  const granularity = propGranularity ?? ('day' as const);

  // Color system based on theme following EcoStep Design System
  const colors = {
    barColor: '#3DDC97', // EcoStep green for primary chart strokes
    gridColor: theme === 'light' ? 'rgba(26, 49, 44, 0.1)' : 'rgba(42, 46, 55, 0.3)',
    textColor: theme === 'light' ? '#1A312C' : '#9CA3AF',
    filterBg: theme === 'light' ? '#F5F6F8' : '#12141A',
    filterActiveBg: theme === 'light' ? '#E8F8EF' : '#1E2B24',
    filterText: theme === 'light' ? 'rgba(26, 49, 44, 0.7)' : '#9CA3AF',
    accent: theme === 'light' ? '#428475' : '#3ED98A',
    border: theme === 'light' ? 'rgba(26, 49, 44, 0.1)' : '#2A2E37',
  };

  /**
   * Filter controls removed - Analytics page controls unified period for all charts
   */

  const showTimeOnXAxis = useMemo(
    () => hasDuplicateFormattedDates(chartData, granularity),
    [chartData, granularity]
  );

  const yAxisScale = useMemo(() => {
    const maxVal = chartData.reduce((m, pt) => Math.max(m, pt.value || 0), 0);
    return computeNiceYAxis(maxVal, { minMax: 0.1, targetSteps: 4 });
  }, [chartData]);

  const subtitle = periodLabel
    ? `Total energy collected per hour or day (${periodLabel})`
    : 'Total energy collected per hour or day (mWh)';

  return (
    <ChartContainer
      title="Energy Generated by Period"
      subtitle={subtitle}
      tooltip={{
        title: "Energy by Period (mWh)",
        description: "Tallies clean energy harvested hour-by-hour or day-by-day. Spot which class transition created the biggest harvest.",
      }}
      isLoading={isLoading}
      error={error}
      isEmpty={isEmpty}
      isSparse={isSparse}
      onRetry={refetch}
      height={chartHeight}
      className={className}
    >
      <ResponsiveContainer width="100%" height={chartHeight} debounce={32}>
        <BarChart
          data={chartData}
          margin={{
            top: 12,
            right: isMobile ? 12 : 20,
            left: isMobile ? 4 : 12,
            bottom: isMobile ? 12 : 4
          }}
        >
          <CartesianGrid vertical={false} strokeDasharray="3 3" stroke={colors.gridColor} />
          <XAxis
            dataKey="timestamp"
            tickFormatter={(timestamp) => formatSmartChartTimestamp(timestamp, granularity, showTimeOnXAxis)}
            stroke={colors.textColor}
            tick={{ fontSize: isMobile ? 11 : 12 }}
            angle={isMobile ? -45 : 0}
            textAnchor={isMobile ? 'end' : 'middle'}
            style={{ fontSize: isMobile ? '11px' : '12px' }}
          />
          <YAxis
            width={isMobile ? 54 : 66}
            label={{
              value: 'Energy (mWh)',
              angle: -90,
              position: 'insideLeft',
              offset: isMobile ? 2 : 0,
              style: {
                fill: colors.textColor,
                fontSize: isMobile ? '11px' : '12px',
                textAnchor: 'middle',
              },
            }}
            stroke={colors.textColor}
            tick={{ fontSize: isMobile ? 11 : 12 }}
            style={{ fontSize: isMobile ? '11px' : '12px' }}
            domain={yAxisScale.domain}
            ticks={yAxisScale.ticks}
            tickFormatter={(v) => Number(v).toFixed(yAxisScale.decimals)}
          />
          <Tooltip
            content={<CustomChartTooltip unit="mWh" />}
            position={{ y: 0 }}
            wrapperStyle={{ zIndex: 1000 }}
            allowEscapeViewBox={{ x: false, y: true }}
            cursor={{ fill: 'rgba(66, 132, 117, 0.1)' }}
            isAnimationActive={false}
          />
          <Bar
            dataKey="value"
            fill={colors.barColor}
            maxBarSize={48}
            radius={[8, 8, 0, 0]}
            isAnimationActive={false}
          />
        </BarChart>
      </ResponsiveContainer>
    </ChartContainer>
  );
});
