/**
 * Manual Role-Based Access Verification Script
 * 
 * Run this script in the browser console on the Dashboard page
 * to verify role-based access requirements for charts.
 * 
 * Instructions:
 * 1. Open the EcoStep Dashboard in your browser
 * 2. Open browser DevTools (F12)
 * 3. Go to Console tab
 * 4. Copy and paste this entire script
 * 5. Press Enter to run
 * 6. Repeat for both public user (unauthenticated) and admin user (authenticated)
 * 
 * Requirements Tested:
 * - 10.1: Both Public_User and System_Administrator can view all charts
 * - 10.3: No admin-only controls in chart components
 * - 10.7: PublicUserBanner displays for unauthenticated users
 * - 10.8: Same dashboard view for both user types
 */

(function verifyRoleBasedAccess() {
  console.log('===================================');
  console.log('Role-Based Access Verification');
  console.log('===================================\n');

  const results = {
    passed: [],
    failed: [],
    warnings: []
  };

  function pass(test) {
    results.passed.push(test);
    console.log(`✅ PASS: ${test}`);
  }

  function fail(test, reason) {
    results.failed.push({ test, reason });
    console.log(`❌ FAIL: ${test}`);
    console.log(`   Reason: ${reason}`);
  }

  function warn(test, reason) {
    results.warnings.push({ test, reason });
    console.log(`⚠️  WARN: ${test}`);
    console.log(`   Reason: ${reason}`);
  }

  // Test 10.1: All charts should be visible
  console.log('\n📊 Requirement 10.1: Verifying all charts are visible...\n');

  const expectedCharts = [
    { title: 'Power Generation Over Time', selector: 'Power Generation' },
    { title: 'Voltage Trend', selector: 'Voltage Trend' },
    { title: 'Current Trend', selector: 'Current Trend' },
    { title: 'Energy Generated by Period', selector: 'Energy Generated' },
    { title: 'Cumulative Energy Generated', selector: 'Cumulative Energy' }
  ];

  expectedCharts.forEach(chart => {
    const elements = Array.from(document.querySelectorAll('h3, h2, h1')).filter(el =>
      el.textContent.includes(chart.selector)
    );

    if (elements.length > 0) {
      pass(`Chart "${chart.title}" is rendered`);
    } else {
      fail(`Chart "${chart.title}" is NOT rendered`, 'Chart title not found in DOM');
    }
  });

  // Test 10.3: No admin-only controls in chart components
  console.log('\n🔒 Requirement 10.3: Checking for admin-only controls in charts...\n');

  const adminKeywords = ['configure', 'delete', 'manage', 'remove', 'edit settings', 'admin'];
  const allButtons = Array.from(document.querySelectorAll('button'));

  // Find the charts container
  const chartsContainer = Array.from(document.querySelectorAll('div')).find(el => {
    const text = el.textContent;
    return text.includes('Power Generation') && text.includes('Voltage Trend');
  });

  if (!chartsContainer) {
    warn('Charts container not found', 'Could not locate the ChartsLayoutContainer');
  } else {
    const chartButtons = Array.from(chartsContainer.querySelectorAll('button'));
    
    const adminButtons = chartButtons.filter(button => {
      const text = button.textContent.toLowerCase();
      return adminKeywords.some(keyword => text.includes(keyword));
    });

    if (adminButtons.length === 0) {
      pass('No admin-only controls found in chart components');
    } else {
      fail('Admin-only controls found in chart components', 
           `Found ${adminButtons.length} buttons with admin keywords: ${adminButtons.map(b => b.textContent).join(', ')}`);
    }

    // Verify filter buttons exist (these are allowed)
    const filterButtons = chartButtons.filter(button => {
      const text = button.textContent.toLowerCase();
      return text.match(/today|days|hourly|daily|weekly|retry/);
    });

    if (filterButtons.length > 0) {
      pass(`Found ${filterButtons.length} allowed filter/control buttons in charts`);
    }
  }

  // Test 10.7: PublicUserBanner visibility
  console.log('\n👤 Requirement 10.7: Checking PublicUserBanner visibility...\n');

  const bannerKeywords = ['create an account', 'sign up', 'register', 'public user'];
  const publicUserBanner = Array.from(document.querySelectorAll('div')).find(el => {
    const text = el.textContent.toLowerCase();
    return bannerKeywords.some(keyword => text.toLowerCase().includes(keyword));
  });

  // Check if user is authenticated (look for profile/logout elements)
  const authIndicators = Array.from(document.querySelectorAll('*')).filter(el =>
    el.textContent.match(/logout|profile|sign out/i)
  );

  const isAuthenticated = authIndicators.length > 0;

  if (publicUserBanner && !isAuthenticated) {
    pass('PublicUserBanner is displayed for unauthenticated user');
  } else if (!publicUserBanner && isAuthenticated) {
    pass('PublicUserBanner is NOT displayed for authenticated user');
  } else if (publicUserBanner && isAuthenticated) {
    fail('PublicUserBanner is displayed for authenticated user', 
         'Banner should only show for public users');
  } else if (!publicUserBanner && !isAuthenticated) {
    warn('PublicUserBanner not found for unauthenticated user', 
         'Could not detect banner - may be a false negative');
  }

  // Test 10.8: Single dashboard view (no separate routes)
  console.log('\n🗺️  Requirement 10.8: Verifying single dashboard view...\n');

  const currentPath = window.location.pathname;
  
  if (currentPath.includes('/dashboard') && !currentPath.match(/public|admin|user/)) {
    pass('Single dashboard route detected (no role-based URL segments)');
  } else if (currentPath.match(/public|admin/)) {
    fail('Separate role-based routes detected', 
         `Current path contains role segment: ${currentPath}`);
  } else {
    warn('Could not determine dashboard route', 
         `Current path: ${currentPath}`);
  }

  // Additional check: Verify ChartsLayoutContainer exists
  const hasChartsLayout = document.body.innerHTML.includes('ChartsLayoutContainer') ||
                         (expectedCharts.filter(chart => 
                           document.body.textContent.includes(chart.selector)
                         ).length >= 4);

  if (hasChartsLayout) {
    pass('ChartsLayoutContainer appears to be rendered');
  } else {
    warn('ChartsLayoutContainer might not be rendered', 
         'Could not confirm chart layout container');
  }

  // Summary
  console.log('\n===================================');
  console.log('VERIFICATION SUMMARY');
  console.log('===================================\n');
  
  console.log(`✅ Passed: ${results.passed.length}`);
  console.log(`❌ Failed: ${results.failed.length}`);
  console.log(`⚠️  Warnings: ${results.warnings.length}\n`);

  if (results.failed.length === 0) {
    console.log('🎉 All tests PASSED! Role-based access is correctly implemented.');
  } else {
    console.log('❌ Some tests FAILED. Review the failures above.');
    console.log('\nFailed Tests:');
    results.failed.forEach(({ test, reason }) => {
      console.log(`  - ${test}: ${reason}`);
    });
  }

  if (results.warnings.length > 0) {
    console.log('\nWarnings:');
    results.warnings.forEach(({ test, reason }) => {
      console.log(`  - ${test}: ${reason}`);
    });
  }

  console.log('\n===================================');
  console.log('User Type Detected:', isAuthenticated ? 'AUTHENTICATED (Admin)' : 'PUBLIC (Unauthenticated)');
  console.log('===================================\n');

  console.log('💡 TIP: Run this script as both a public user and an authenticated admin');
  console.log('       to verify both scenarios work correctly.\n');

  return {
    passed: results.passed.length,
    failed: results.failed.length,
    warnings: results.warnings.length,
    isAuthenticated,
    results
  };
})();
